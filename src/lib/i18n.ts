const dicts: Record<Language, Dict> = { en, hi };

export type TKey = keyof Dict;

export function translate(lang: Language, key: TKey): string {
  return dicts[lang][key] ?? en[key];
}

export function useT() {
  const { profile } = useProfile();
  const lang: Language = profile?.language ?? 'en';
  return {
    lang,
    t: (key: TKey) => translate(lang, key),
    /** Pick the Hindi variant of a content string when available. */
    pick: (enText: string, hiText?: string) => (lang === 'hi' && hiText ? hiText : enText),
  };
}
